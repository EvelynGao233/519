"""Ensemble of three headline classifiers: Fox News vs NBC News.

  1. TfidfLR              hashed TF-IDF (word 1-3 grams, char 1-5 grams, length) + logistic regression
  2. FastTextNN           hashed sub-word EmbeddingBag + MLP, trained in PyTorch
  3. DistilBertClassifier DistilBERT-base-uncased fine-tuned on our data, re-implemented in plain
                          PyTorch (the backend has no `transformers`), with its WordPiece tokenizer

Model.predict averages the three models' P(NBC) with equal weights and thresholds at 0.5.
There is no lookup of training headlines. All tensors have fixed shapes, so Model() builds
with no arguments and model.pt loads as one state dict (keys tfidf.*, fasttext.*, bert.*).

GENERATED by src/build_final.py from submission/, submission_nn/ and submission_bert/.
"""
from __future__ import annotations

import math
import re
import unicodedata
import zlib
from typing import Dict, Iterable, List, Tuple

import numpy as np
import torch
import torch.nn.functional as F
from torch import nn

LABELS = ["FoxNews", "NBC"]


# ============================================================================= TF-IDF + logistic regression
TF_N_WORD = 2 ** 20
TF_N_CHAR = 2 ** 20
TF_N_FEAT = TF_N_WORD + TF_N_CHAR


def _tf_hash(s: str, mod: int) -> int:
    return zlib.crc32(s.encode("utf-8")) % mod


def _tf_word_ngrams(words: List[str], n_max: int = 3) -> List[str]:
    out = []
    for n in range(1, n_max + 1):
        for i in range(len(words) - n + 1):
            out.append(" ".join(words[i : i + n]))
    out.append(f"__len{min(len(words), 20)}")  # headline length bucket
    return out


def _tf_char_ngrams(words: List[str], n_min: int = 1, n_max: int = 5) -> List[str]:
    out = []
    for w in words:
        w = f" {w} "
        for n in range(n_min, n_max + 1):
            for i in range(len(w) - n + 1):
                out.append(w[i : i + n])
    return out


def tfidf_featurize(texts: Iterable[str]):
    """texts -> (rows, cols, counts) COO triplets over TF_N_FEAT hashed buckets.

    Returns raw term counts; tf/idf weighting is applied in `tfidf_weight`.
    """
    rows, cols, vals = [], [], []
    for r, t in enumerate(texts):
        words = re.sub(r"[^a-z' ]+", " ", str(t).lower()).split()
        counts: dict = {}
        for g in _tf_word_ngrams(words):
            k = _tf_hash("w" + g, TF_N_WORD)
            counts[k] = counts.get(k, 0) + 1
        for g in _tf_char_ngrams(words):
            k = TF_N_WORD + _tf_hash("c" + g, TF_N_CHAR)
            counts[k] = counts.get(k, 0) + 1
        for k, c in counts.items():
            rows.append(r)
            cols.append(k)
            vals.append(c)
    return np.array(rows, dtype=np.int64), np.array(cols, dtype=np.int64), np.array(vals, dtype=np.float32)


def tfidf_weight(rows, cols, counts, idf: np.ndarray, n_rows: int):
    """Sublinear tf * idf, then L2-normalise the word block and char block separately."""
    v = (1.0 + np.log(counts)) * idf[cols]
    is_char = cols >= TF_N_WORD
    seg = rows * 2 + is_char  # (row, block) id
    sq = np.bincount(seg, weights=v * v, minlength=n_rows * 2)
    norm = np.sqrt(sq[seg])
    v = np.where(norm > 0, v / np.maximum(norm, 1e-12), 0.0)
    return v.astype(np.float32)


class TfidfLR(nn.Module):
    """Hashed TF-IDF + logistic regression. No lookup of training headlines."""

    def __init__(self) -> None:
        super().__init__()
        self.register_buffer("idf", torch.ones(TF_N_FEAT))
        self.register_buffer("coef", torch.zeros(TF_N_FEAT))
        self.register_buffer("bias", torch.zeros(1))

    def logits(self, texts: List[str]) -> torch.Tensor:
        """Decision value for each text (>0 means NBC)."""
        rows, cols, counts = tfidf_featurize(texts)
        v = tfidf_weight(rows, cols, counts, self.idf.numpy(), len(texts))
        score = np.bincount(rows, weights=v * self.coef.numpy()[cols], minlength=len(texts))
        return torch.from_numpy(score).float() + self.bias

    def forward(self, batch) -> torch.Tensor:
        s = self.logits(list(batch))
        return torch.stack([-s / 2, s / 2], dim=-1)

    @torch.no_grad()
    def predict(self, batch) -> List[str]:
        s = self.logits(list(batch))
        return [LABELS[int(x > 0)] for x in s]


# ============================================================================= fastText-style neural network
FT_N_BUCKETS = 2 ** 20
FT_EMB_DIM = 64
FT_HIDDEN = 128


def _ft_hash(s: str) -> int:
    return zlib.crc32(s.encode("utf-8")) % FT_N_BUCKETS


def ft_token_ids(text: str) -> List[int]:
    words = re.sub(r"[^a-z' ]+", " ", str(text).lower()).split()
    ids = [_ft_hash("w" + w) for w in words]
    ids += [_ft_hash("b" + a + " " + b) for a, b in zip(words, words[1:])]
    for w in words:
        w = f"<{w}>"
        for n in (3, 4, 5):
            ids += [_ft_hash("c" + w[i : i + n]) for i in range(len(w) - n + 1)]
    ids.append(_ft_hash(f"len{min(len(words), 20)}"))
    return ids


def ft_batch_inputs(texts: Iterable[str]) -> Tuple[torch.Tensor, torch.Tensor]:
    flat: List[int] = []
    offsets: List[int] = []
    for t in texts:
        offsets.append(len(flat))
        flat.extend(ft_token_ids(t))
    return torch.tensor(flat, dtype=torch.long), torch.tensor(offsets, dtype=torch.long)


class FastTextNN(nn.Module):
    def __init__(self) -> None:
        super().__init__()
        self.embedding = nn.EmbeddingBag(FT_N_BUCKETS, FT_EMB_DIM, mode="mean", sparse=True)
        self.mlp = nn.Sequential(
            nn.Linear(FT_EMB_DIM, FT_HIDDEN),
            nn.ReLU(),
            nn.Dropout(0.2),
            nn.Linear(FT_HIDDEN, 2),
        )

    def forward_ids(self, flat: torch.Tensor, offsets: torch.Tensor) -> torch.Tensor:
        return self.mlp(self.embedding(flat, offsets))

    def forward(self, batch) -> torch.Tensor:
        flat, offsets = ft_batch_inputs(list(batch))
        return self.forward_ids(flat, offsets)

    @torch.no_grad()
    def proba_nbc(self, texts: List[str], bs: int = 1024) -> np.ndarray:
        self.eval()
        out = []
        for i in range(0, len(texts), bs):
            out.append(torch.softmax(self.forward(texts[i : i + bs]), -1)[:, 1].numpy())
        return np.concatenate(out) if out else np.zeros(0)

    @torch.no_grad()
    def predict(self, batch) -> List[str]:
        self.eval()
        logits = self.forward(list(batch))
        return [LABELS[int(i)] for i in logits.argmax(-1)]


# ============================================================================= DistilBERT in plain PyTorch
VOCAB_SIZE = 30522
VOCAB_BYTES = 231507  # len("\n".join(distilbert-base-uncased vocab).encode("utf-8"))
DIM, N_LAYERS, N_HEADS, HIDDEN_DIM, MAX_POS = 768, 6, 12, 3072, 512
MAX_LEN = 64  # headlines are short; [CLS] + tokens + [SEP] is truncated to this
CLS, SEP, PAD, UNK = "[CLS]", "[SEP]", "[PAD]", "[UNK]"


# ----------------------------------------------------------------------------- tokenizer
def _is_punct(ch: str) -> bool:
    cp = ord(ch)
    if 33 <= cp <= 47 or 58 <= cp <= 64 or 91 <= cp <= 96 or 123 <= cp <= 126:
        return True
    return unicodedata.category(ch).startswith("P")


def _is_cjk(cp: int) -> bool:
    return (0x4E00 <= cp <= 0x9FFF or 0x3400 <= cp <= 0x4DBF or 0x20000 <= cp <= 0x2A6DF
            or 0x2A700 <= cp <= 0x2B73F or 0x2B740 <= cp <= 0x2B81F or 0x2B820 <= cp <= 0x2CEAF
            or 0xF900 <= cp <= 0xFAFF or 0x2F800 <= cp <= 0x2FA1F)


def basic_tokenize(text: str) -> List[str]:
    """BERT BasicTokenizer (uncased): clean, split CJK, lowercase, strip accents, split punctuation."""
    out = []
    for ch in str(text):
        cp = ord(ch)
        if cp == 0 or cp == 0xFFFD or (unicodedata.category(ch).startswith("C") and ch not in "\t\n\r"):
            continue
        if _is_cjk(cp):
            out.append(f" {ch} ")
        elif ch.isspace():
            out.append(" ")
        else:
            out.append(ch)
    tokens = []
    for word in "".join(out).lower().split():
        word = "".join(c for c in unicodedata.normalize("NFD", word) if unicodedata.category(c) != "Mn")
        cur = ""
        for ch in word:
            if _is_punct(ch):
                if cur:
                    tokens.append(cur)
                    cur = ""
                tokens.append(ch)
            else:
                cur += ch
        if cur:
            tokens.append(cur)
    return tokens


def wordpiece(word: str, vocab: Dict[str, int]) -> List[int]:
    if len(word) > 100:
        return [vocab[UNK]]
    ids, start = [], 0
    while start < len(word):
        end, cur = len(word), None
        while start < end:
            piece = word[start:end] if start == 0 else "##" + word[start:end]
            if piece in vocab:
                cur = vocab[piece]
                break
            end -= 1
        if cur is None:
            return [vocab[UNK]]
        ids.append(cur)
        start = end
    return ids


# ----------------------------------------------------------------------------- model
class Embeddings(nn.Module):
    def __init__(self):
        super().__init__()
        self.word_embeddings = nn.Embedding(VOCAB_SIZE, DIM, padding_idx=0)
        self.position_embeddings = nn.Embedding(MAX_POS, DIM)
        self.LayerNorm = nn.LayerNorm(DIM, eps=1e-12)
        self.dropout = nn.Dropout(0.1)

    def forward(self, ids):
        pos = torch.arange(ids.shape[1], device=ids.device).unsqueeze(0)
        return self.dropout(self.LayerNorm(self.word_embeddings(ids) + self.position_embeddings(pos)))


class MultiHeadSelfAttention(nn.Module):
    def __init__(self):
        super().__init__()
        self.q_lin, self.k_lin = nn.Linear(DIM, DIM), nn.Linear(DIM, DIM)
        self.v_lin, self.out_lin = nn.Linear(DIM, DIM), nn.Linear(DIM, DIM)

    def forward(self, x, mask):
        b, t, _ = x.shape
        split = lambda z: z.view(b, t, N_HEADS, DIM // N_HEADS).transpose(1, 2)
        q, k, v = split(self.q_lin(x)), split(self.k_lin(x)), split(self.v_lin(x))
        ctx = F.scaled_dot_product_attention(q, k, v, attn_mask=mask[:, None, None, :].bool())
        return self.out_lin(ctx.transpose(1, 2).reshape(b, t, DIM))


class FFN(nn.Module):
    def __init__(self):
        super().__init__()
        self.lin1, self.lin2 = nn.Linear(DIM, HIDDEN_DIM), nn.Linear(HIDDEN_DIM, DIM)

    def forward(self, x):
        return self.lin2(F.gelu(self.lin1(x)))


class TransformerBlock(nn.Module):
    def __init__(self):
        super().__init__()
        self.attention = MultiHeadSelfAttention()
        self.sa_layer_norm = nn.LayerNorm(DIM, eps=1e-12)
        self.ffn = FFN()
        self.output_layer_norm = nn.LayerNorm(DIM, eps=1e-12)

    def forward(self, x, mask):
        x = self.sa_layer_norm(x + self.attention(x, mask))
        return self.output_layer_norm(x + self.ffn(x))


class Transformer(nn.Module):
    def __init__(self):
        super().__init__()
        self.layer = nn.ModuleList([TransformerBlock() for _ in range(N_LAYERS)])

    def forward(self, x, mask):
        for blk in self.layer:
            x = blk(x, mask)
        return x


class DistilBert(nn.Module):
    def __init__(self):
        super().__init__()
        self.embeddings = Embeddings()
        self.transformer = Transformer()

    def forward(self, ids, mask):
        return self.transformer(self.embeddings(ids), mask)


class DistilBertClassifier(nn.Module):
    def __init__(self) -> None:
        super().__init__()
        self.distilbert = DistilBert()
        self.pre_classifier = nn.Linear(DIM, DIM)
        self.classifier = nn.Linear(DIM, 2)
        self.dropout = nn.Dropout(0.2)
        self.register_buffer("vocab_bytes", torch.zeros(VOCAB_BYTES, dtype=torch.uint8))
        self._vocab: Dict[str, int] | None = None

    # -- tokenizer -----------------------------------------------------------
    def vocab(self) -> Dict[str, int]:
        if self._vocab is None:
            raw = bytes(self.vocab_bytes.tolist()).decode("utf-8")
            toks = raw.split("\n")
            if len(toks) != VOCAB_SIZE:
                raise RuntimeError("vocab_bytes not loaded: load model.pt before predicting")
            self._vocab = {t: i for i, t in enumerate(toks)}
        return self._vocab

    def encode(self, texts: List[str]):
        v = self.vocab()
        seqs = []
        for t in texts:
            ids = [i for w in basic_tokenize(t) for i in wordpiece(w, v)][: MAX_LEN - 2]
            seqs.append([v[CLS]] + ids + [v[SEP]])
        width = max(len(s) for s in seqs)
        ids = torch.zeros(len(seqs), width, dtype=torch.long)
        mask = torch.zeros(len(seqs), width, dtype=torch.long)
        for i, s in enumerate(seqs):
            ids[i, : len(s)] = torch.tensor(s)
            mask[i, : len(s)] = 1
        return ids, mask

    # -- model ---------------------------------------------------------------
    def forward_ids(self, ids, mask):
        h = self.distilbert(ids, mask)[:, 0]
        return self.classifier(self.dropout(F.relu(self.pre_classifier(h))))

    def forward(self, batch) -> torch.Tensor:
        ids, mask = self.encode(list(batch))
        return self.forward_ids(ids, mask)

    @torch.no_grad()
    def predict(self, batch) -> List[str]:
        self.eval()
        return [LABELS[int(i)] for i in self.forward(list(batch)).argmax(-1)]


# ============================================================================= ensemble
class Model(nn.Module):
    def __init__(self) -> None:
        super().__init__()
        self.tfidf = TfidfLR()
        self.fasttext = FastTextNN()
        self.bert = DistilBertClassifier()

    @torch.no_grad()
    def member_probs(self, texts: List[str]) -> torch.Tensor:
        """[n, 3] P(NBC) from tfidf, fasttext, bert."""
        p_tfidf = torch.sigmoid(self.tfidf.logits(texts))
        p_ft = torch.softmax(self.fasttext.forward(texts), -1)[:, 1]
        p_bert = torch.softmax(self.bert.forward(texts), -1)[:, 1]
        return torch.stack([p_tfidf, p_ft, p_bert], dim=1)

    def forward(self, batch) -> torch.Tensor:
        p = self.member_probs(list(batch)).mean(1).clamp(1e-6, 1 - 1e-6)
        return torch.stack([torch.log1p(-p), torch.log(p)], dim=-1)

    @torch.no_grad()
    def predict(self, batch) -> List[str]:
        self.eval()
        p = self.member_probs(list(batch)).mean(1)
        return [LABELS[int(x > 0.5)] for x in p]


def get_model() -> Model:
    return Model()
