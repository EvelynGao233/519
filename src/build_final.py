"""Assemble the 3-model ensemble into ONE model.py + ONE model.pt (submission_final/).

The leaderboard imports a single model.py by path, so the three sub-models' code is
merged into one file (names prefixed where they would clash), and the three state dicts
are merged under the prefixes tfidf. / fasttext. / bert. -- the FAQ's recipe for ensembles.

  python src/build_final.py                       # final weights
  python src/build_final.py --linear experiments/tmp.pt --out-dir experiments/final_honest
                                                  # honest variant (no val20 in any sub-model)
"""
from __future__ import annotations

import argparse
import re
import shutil
from pathlib import Path

import torch

ROOT = Path(__file__).resolve().parents[1]

HEADER = '''"""Ensemble of three headline classifiers: Fox News vs NBC News.

  1. TfidfLR              hashed TF-IDF (word 1-3 grams, char 1-5 grams, length) + logistic regression
  2. FastTextNN           hashed sub-word EmbeddingBag + MLP, trained in PyTorch
  3. DistilBertClassifier DistilBERT-base-uncased fine-tuned on our data, re-implemented in plain
                          PyTorch (the backend has no `transformers`), with its WordPiece tokenizer

Model.predict averages the three models' P(NBC) with equal weights and thresholds at 0.5.
There is no lookup of training headlines. All tensors have fixed shapes, so Model() builds
with no arguments and model.pt loads as one state dict (keys tfidf.*, fasttext.*, bert.*).

GENERATED by src/build_final.py from submission/, submission_nn/ and submission_bert/.
"""
from __future__ import annotations

import math
import re
import unicodedata
import zlib
from typing import Dict, Iterable, List, Tuple

import numpy as np
import torch
import torch.nn.functional as F
from torch import nn

LABELS = ["FoxNews", "NBC"]
'''

FOOTER = '''

# ============================================================================= ensemble
class Model(nn.Module):
    def __init__(self) -> None:
        super().__init__()
        self.tfidf = TfidfLR()
        self.fasttext = FastTextNN()
        self.bert = DistilBertClassifier()

    @torch.no_grad()
    def member_probs(self, texts: List[str]) -> torch.Tensor:
        """[n, 3] P(NBC) from tfidf, fasttext, bert."""
        p_tfidf = torch.sigmoid(self.tfidf.logits(texts))
        p_ft = torch.softmax(self.fasttext.forward(texts), -1)[:, 1]
        p_bert = torch.softmax(self.bert.forward(texts), -1)[:, 1]
        return torch.stack([p_tfidf, p_ft, p_bert], dim=1)

    def forward(self, batch) -> torch.Tensor:
        p = self.member_probs(list(batch)).mean(1).clamp(1e-6, 1 - 1e-6)
        return torch.stack([torch.log1p(-p), torch.log(p)], dim=-1)

    @torch.no_grad()
    def predict(self, batch) -> List[str]:
        self.eval()
        p = self.member_probs(list(batch)).mean(1)
        return [LABELS[int(x > 0.5)] for x in p]


def get_model() -> Model:
    return Model()
'''

PARTS = [
    ("submission/model.py", "TF-IDF + logistic regression", {
        "_h": "_tf_hash", "N_WORD": "TF_N_WORD", "N_CHAR": "TF_N_CHAR", "N_FEAT": "TF_N_FEAT",
        "_word_ngrams": "_tf_word_ngrams", "_char_ngrams": "_tf_char_ngrams",
        "featurize": "tfidf_featurize", "weight": "tfidf_weight", "Model": "TfidfLR"}),
    ("submission_nn/model.py", "fastText-style neural network", {
        "_h": "_ft_hash", "N_BUCKETS": "FT_N_BUCKETS", "EMB_DIM": "FT_EMB_DIM", "HIDDEN": "FT_HIDDEN",
        "token_ids": "ft_token_ids", "batch_inputs": "ft_batch_inputs", "Model": "FastTextNN"}),
    ("submission_bert/model.py", "DistilBERT in plain PyTorch", {"Model": "DistilBertClassifier"}),
]


def body(path: Path, renames: dict) -> str:
    src = path.read_text(encoding="utf-8")
    src = re.sub(r'^""".*?"""\n', "", src, count=1, flags=re.S)          # module docstring
    src = re.sub(r"\ndef get_model\(\).*", "\n", src, flags=re.S)        # factory
    keep = []
    for line in src.splitlines():
        if re.match(r"(from __future__|import |from \S+ import )", line) or line.startswith("LABELS ="):
            continue
        keep.append(line)
    src = "\n".join(keep).strip("\n")
    for old, new in renames.items():
        src = re.sub(rf"\b{re.escape(old)}\b", new, src)
    return src


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--linear", default=str(ROOT / "submission/model.pt"))
    p.add_argument("--nn", default=str(ROOT / "submission_nn/model.pt"))
    p.add_argument("--bert", default=str(ROOT / "submission_bert/model.pt"))
    p.add_argument("--out-dir", default=str(ROOT / "submission_final"))
    a = p.parse_args()
    out = Path(a.out_dir)
    out.mkdir(parents=True, exist_ok=True)

    code = HEADER
    for rel, title, renames in PARTS:
        code += f"\n\n# ============================================================================= {title}\n"
        code += body(ROOT / rel, renames) + "\n"
    code += FOOTER
    (out / "model.py").write_text(code, encoding="utf-8")
    shutil.copy(ROOT / "submission/preprocess.py", out / "preprocess.py")

    sd = {}
    for prefix, path in [("tfidf", a.linear), ("fasttext", a.nn), ("bert", a.bert)]:
        part = torch.load(path, map_location="cpu")
        sd.update({f"{prefix}.{k}": v for k, v in part.items() if not k.startswith("memo_")})
    torch.save(sd, out / "model.pt")
    print(f"wrote {out / 'model.py'} and {out / 'model.pt'} ({len(sd)} tensors)")


if __name__ == "__main__":
    main()
